/*
 * convrot_int8_linear_plugin.cpp — IPluginV3 implementation for ConvRotInt8Linear.
 *
 * Phase 1 architecture — fully-fused Triton AOT kernel via CUDA Driver API:
 *
 *   enqueue() pipeline (single Triton kernel launch):
 *     1. ConvRot activation rotation via in-register H_4 Kronecker butterfly
 *     2. Per-row dynamic INT8 quantization
 *     3. INT8 × INT8 → INT32 GEMM via Tensor Cores (tl.dot)
 *     4. Dequant + bias + FP16 cast epilogue
 *
 * Rotation design (butterfly, NOT H-matrix matmul):
 *   The Hadamard rotation H_{GROUP_SIZE} is decomposed into log_4(GROUP_SIZE)
 *   successive H_4 butterfly stages, all performed in registers. This avoids
 *   materializing the full [GROUP_SIZE × GROUP_SIZE] H matrix in shared memory
 *   (which would be 128 KB for GROUP_SIZE=256 in FP16 — exceeding the sm_86
 *   99 KB hardware limit and causing cuLaunchKernel to fail with
 *   CUDA_ERROR_INVALID_VALUE). The butterfly approach works uniformly for all
 *   valid group sizes {4, 16, 64, 256, 1024} and uses zero shared memory for
 *   rotation. Fusion is preserved — all butterfly ops are elementwise on
 *   register tiles.
 *
 * Cubin dispatch:
 *   At onShapeChange(), the plugin loads the AOT-compiled cubin matching the
 *   runtime (tactic, group_size, has_bias) tuple via cuModuleLoadData. Cubin
 *   names follow the pattern kCONVROT_INT8_KERNEL_{TILE}_G{GROUP}_{BIAS|NOBIAS}.
 *   The cubins are generated by tools/onnx-export/compile_triton_plugin.py and
 *   embedded in engine/src/plugins/assets/convrot_int8_kernel_cubin.h.
 *
 * Shared-memory opt-in:
 *   Triton GEMM kernels with multi-stage pipelining bake >48 KB of static
 *   shared memory into the cubin. We query the static shared-mem size via
 *   cuFuncGetAttribute and opt in to the larger per-block carveout via
 *   cuFuncSetAttribute(MAX_DYNAMIC_SHARED_SIZE_BYTES) before launch. Without
 *   this opt-in, cuLaunchKernel returns CUDA_ERROR_INVALID_VALUE.
 *
 * Build vs Runtime:
 *   - Build: TRT calls configurePlugin() + getWorkspaceSize() (returns 0).
 *   - Runtime: onShapeChange() loads cubin + opts in to shared mem;
 *     enqueue() launches the fused kernel.
 */

