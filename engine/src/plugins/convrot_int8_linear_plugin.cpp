int32_t ConvRotInt8LinearPlugin::onShapeChange(
    nvinfer1::PluginTensorDesc const* in, int32_t nbInputs,
    nvinfer1::PluginTensorDesc const* out, int32_t nbOutputs) noexcept {
    hotstep::diag::log("[ConvRotInt8Linear] onShapeChange ENTER: nbInputs=%d, nbOutputs=%d, "
                     "serialized(group_size=%d, in_features=%d, out_features=%d, has_bias=%d, "
                     "input_dtype=%s, output_dtype=%s, m_module=%p, m_tactic=%d)\n",
                     nbInputs, nbOutputs,
                     m_group_size, m_in_features, m_out_features, m_has_bias,
                     dtypeNameFromId(m_input_dtype_id), dtypeNameFromId(m_output_dtype_id),
                     m_module, m_tactic);

    if (nbInputs < (m_has_bias ? 4 : 3) || nbOutputs < 1) {
        hotstep::diag::log("[ConvRotInt8Linear] onShapeChange REJECT: nbInputs=%d < required=%d "
                         "OR nbOutputs=%d < 1. m_has_bias=%d.\n",
                         nbInputs, (m_has_bias ? 4 : 3), nbOutputs, m_has_bias);
        return -1;
    }
    // Extract M, K, N from the descriptors.
    (void)out;
    auto const& x_desc = in[0].dims;
    int64_t runtimeM = flattenedRows(x_desc);
    if (runtimeM <= 0 || runtimeM > std::numeric_limits<int32_t>::max()) {
        hotstep::diag::log("[ConvRotInt8Linear] onShapeChange REJECT: runtimeM=%lld is out of "
                         "range (must be in [1, %d]).\n",
                         (long long)runtimeM, std::numeric_limits<int32_t>::max());
        return -1;
    }
    m_M = static_cast<int32_t>(runtimeM);
    m_K = lastDim(x_desc);
    m_N = m_out_features;

    hotstep::diag::log("[ConvRotInt8Linear] onShapeChange shapes: M=%d, K=%d (expected=%d), N=%d, "
                     "x_desc.nbDims=%d, x_desc.d=[",
                     m_M, m_K, m_in_features, m_N, x_desc.nbDims);
    for (int32_t i = 0; i < x_desc.nbDims; ++i) {
        hotstep::diag::log("%s%d", (i ? "," : ""), x_desc.d[i]);
    }
    hotstep::diag::log("]\n");

    if (m_K != m_in_features) {
        hotstep::diag::log("[ConvRotInt8Linear] onShapeChange REJECT: runtime K=%d != serialized "
                         "in_features=%d. The ONNX input shape does not match the build-time "
                         "contract.\n",
                         m_K, m_in_features);
        return -1;
    }
    if (!validGroupSize(m_group_size, m_K)) {
        hotstep::diag::log("[ConvRotInt8Linear] onShapeChange REJECT: group_size=%d not valid "
                         "for K=%d (must divide K evenly, or be 0).\n",
                         m_group_size, m_K);
        return -1;
    }
    if (m_M <= 0 || m_K <= 0 || m_N <= 0) {
        hotstep::diag::log("[ConvRotInt8Linear] onShapeChange REJECT: non-positive dim "
                         "(M=%d, K=%d, N=%d).\n", m_M, m_K, m_N);
        return -1;
    }

    // Initialize Triton compiled kernel lazily for the new shapes/tactics.
    // The cubin is keyed only by (tile, group_size, has_bias, dtype) — not by
    // M/K/N — so we only need to re-init when the previous module is missing
    // (e.g. first call after clone() or destroyTriton()).
    if (!m_module) {
        if (!initTriton()) {
            hotstep::diag::log(
                         "[ConvRotInt8Linear] onShapeChange FAILURE: initTriton() failed for "
                         "group_size=%d, in_features=%d, out_features=%d, has_bias=%d, "
                         "M=%d, K=%d, N=%d, input_dtype=%s, output_dtype=%s.\n",
                         m_group_size, m_in_features, m_out_features, m_has_bias,
                         m_M, m_K, m_N,
                         dtypeNameFromId(m_input_dtype_id),
                         dtypeNameFromId(m_output_dtype_id));
            // Force-flush BEFORE returning the error code — TRT's PluginV3Runner
            // assertion may abort the process before our static destructor runs.
            hotstep::diag::flush();
            return -1;
        }
    } else {
        hotstep::diag::log("[ConvRotInt8Linear] onShapeChange: reusing existing cubin module=%p "
                         "(no re-init needed).\n", m_module);
    }
    hotstep::diag::log("[ConvRotInt8Linear] onShapeChange OK — returning 0.\n");
    return 0;
}

int32_t ConvRotInt8LinearPlugin::enqueue(
    nvinfer1::PluginTensorDesc const* inputDesc,
    nvinfer1::PluginTensorDesc const* outputDesc,
    void const* const* inputs, void* const* outputs,
    void* workspace, cudaStream_t stream) noexcept {
    try {
        (void)inputDesc;
        (void)outputDesc;
        (void)workspace;
        int32_t M = m_M, K = m_K, N = m_N;
        if (M <= 0 || K <= 0 || N <= 0) {
            hotstep::diag::log("[ConvRotInt8Linear] enqueue REJECT: non-positive dim "
                             "(M=%d, K=%d, N=%d) — onShapeChange was not called or failed.\n",
                             M, K, N);
            return -1;
        }

        if (!m_kernelFunc) {
            hotstep::diag::log("[ConvRotInt8Linear] enqueue REJECT: m_kernelFunc=nullptr. "
                             "initTriton() did not run successfully (check log for "
                             "onShapeChange / initTriton errors above).\n");
            return -1;
        }

        hotstep::diag::log("[ConvRotInt8Linear] enqueue ENTER: M=%d, K=%d, N=%d, tactic=%d, "
                         "group_size=%d, has_bias=%d, input_dtype=%s, output_dtype=%s, "
                         "stream=%p, kernelFunc=%p\n",
                         M, K, N, m_tactic, m_group_size, m_has_bias,
                         dtypeNameFromId(m_input_dtype_id), dtypeNameFromId(m_output_dtype_id),
                         (void*)stream, (void*)m_kernelFunc);

        void const* x_ptr      = inputs[0];
        int8_t const* wq_ptr   = static_cast<int8_t const*>(inputs[1]);
        float const* ws_ptr    = static_cast<float const*>(inputs[2]);
        void const* bias_ptr   = m_has_bias ? inputs[3] : nullptr;
        void* y_ptr            = outputs[0];

        hotstep::diag::log("[ConvRotInt8Linear] enqueue ptrs: x=%p, wq=%p, ws=%p, bias=%p, y=%p\n",
                         (void*)x_ptr, (void*)wq_ptr, (void*)ws_ptr, (void*)bias_ptr, (void*)y_ptr);

        // Strides (tensors are row-major kLINEAR format)
        int32_t stride_xm = K;
        int32_t stride_xk = 1;
        int32_t stride_wn = K;
        int32_t stride_wk = 1;
        int32_t stride_ym = N;
        int32_t stride_yn = 1;

        // Block dimensions matching the AOT-compiled cubin. The compile script
        // picks the best (BLOCK_M, BLOCK_N, num_stages) combo per config to
        // maximize pipelining within the device's shared-memory limit. The
        // actual values are baked into the cubin header as _BLOCK_M / _BLOCK_N
        // constants and loaded by initTriton() into m_block_m / m_block_n.
        //
        // M==1 always uses the M1 kernel (BLOCK_M=1). For M>1, BLOCK_M may be
        // 128 (FP16IO / G0 / G64 with ns=3), 64 (G256 FP32IO with ns=2), or
        // 32 (fallback with ns=3). The grid math below handles all cases.
        bool const use_m1_specialized = (M == 1);
        int32_t block_m = use_m1_specialized ? 1 : m_block_m;
        int32_t block_n = use_m1_specialized ? m_block_n : m_block_n;

        // Grid parameters for 1D program tiling in Triton.
        unsigned int gridX = use_m1_specialized
            ? static_cast<unsigned int>((N + block_n - 1) / block_n)
            : static_cast<unsigned int>(((M + block_m - 1) / block_m) * ((N + block_n - 1) / block_n));
        unsigned int gridY = 1;
        unsigned int gridZ = 1;

        // Triton compiled kernels are 1D blocks of num_warps * 32 threads
        unsigned int blockX = 4 * 32; // 128 threads (4 warps)
        unsigned int blockY = 1;
        unsigned int blockZ = 1;

        // Triton compiler automatically appends two global pointer parameters
        // (global scratch / cluster scratch) to every compiled kernel signature.
        // We must provide dummy null pointers for these 2 extra arguments, otherwise
        // cuLaunchKernel reads uninitialized stack memory past args[13] and fails
        // with CUDA_ERROR_INVALID_VALUE (invalid argument).
        void* triton_scratch1 = nullptr;
        void* triton_scratch2 = nullptr;

        // Setup kernel execution arguments (16 args — 14 kernel args + 2 Triton scratch args)
        void* args[] = {
            &x_ptr,
            &wq_ptr,
            &y_ptr,
            &ws_ptr,
            &bias_ptr,
            &M,
            &N,
            &K,
            &stride_xm,
            &stride_xk,
            &stride_wn,
            &stride_wk,
            &stride_ym,
            &stride_yn,
            &triton_scratch1,
            &triton_scratch2
        };

        // Launch the compiled Triton kernel via CUDA Driver API.
        // Modern Triton 3.x uses DYNAMIC shared memory (.extern .shared
        // global_smem[]). We pass m_shared_bytes — the kernel's ACTUAL
        // dynamic shared-memory requirement as reported by Triton's compile
        // metadata and embedded in the cubin header — instead of the device's
        // opt-in ceiling. This is critical: cuLaunchKernel only validates
        //   sharedMemBytes <= cuFuncSetAttribute(MAX_DYNAMIC_SHARED_SIZE_BYTES)
        // and does NOT validate that sharedMemBytes >= the kernel's actual
        // requirement. If we passed a value smaller than the kernel needs
        // (e.g. by passing 0, or by passing a stale value from a header
        // generated before the _SHARED constants existed), cuLaunchKernel
        // would still return CUDA_SUCCESS, but the kernel would fault
        // mid-execution with an out-of-bounds shared memory access —
        // surfaced asynchronously as CUDA_ERROR_ILLEGAL_INSTRUCTION (700)
        // on the next CUDA Driver API call.
        unsigned int const dynamicSmemBytes = static_cast<unsigned int>(m_shared_bytes);
        hotstep::diag::log("[ConvRotInt8Linear] enqueue cuLaunchKernel: kernel=%s, grid=(%u,%u,%u), "
                         "block=(%u,%u,%u), sharedMemBytes=%u (kernel requirement), num_args=16\n",
                         use_m1_specialized ? "fused_convrot_gemm_rowwise_m1_kernel" : "fused_convrot_gemm_rowwise_kernel",
                         gridX, gridY, gridZ, blockX, blockY, blockZ, dynamicSmemBytes);
        CUresult status = cuLaunchKernel(
            static_cast<CUfunction>(m_kernelFunc),
            gridX, gridY, gridZ,
            blockX, blockY, blockZ,
            dynamicSmemBytes, // sharedMemBytes — kernel's actual dynamic shared-mem requirement
            stream,
            args,
            nullptr
        );

        if (status != CUDA_SUCCESS) {
            char const* err_str = "unknown";
            cuGetErrorString(status, &err_str);
            cudaError_t async_status = cudaPeekAtLastError();
            int shared_bytes_static = 0;
            cuFuncGetAttribute(&shared_bytes_static,
                               CU_FUNC_ATTRIBUTE_SHARED_SIZE_BYTES,
                               static_cast<CUfunction>(m_kernelFunc));
            // Also query num_regs and max_threads_per_block — these are the
            // most common reasons for cuLaunchKernel returning CUDA_ERROR_INVALID_VALUE
            // when the cubin compiles but can't be launched on the device.
            int num_regs = 0, max_threads_per_block = 0;
            cuFuncGetAttribute(&num_regs,
                               CU_FUNC_ATTRIBUTE_NUM_REGS,
                               static_cast<CUfunction>(m_kernelFunc));
            cuFuncGetAttribute(&max_threads_per_block,
                               CU_FUNC_ATTRIBUTE_MAX_THREADS_PER_BLOCK,
                               static_cast<CUfunction>(m_kernelFunc));
            hotstep::diag::log(
                         "[ConvRotInt8Linear] enqueue FAILURE: cuLaunchKernel failed: %s "
                         "(code=%d, tactic=%d, group_size=%d, grid=(%u,%u,%u), block=(%u,%u,%u), "
                         "shared_mem_requested=%u, shared_mem_static=%d bytes, num_regs=%d, "
                         "max_threads_per_block=%d, cudaPeekAtLastError=%d (%s), M=%d, K=%d, N=%d, "
                         "input_dtype=%s, output_dtype=%s)\n",
                         err_str, status, m_tactic, m_group_size,
                         gridX, gridY, gridZ,
                         blockX, blockY, blockZ,
                         dynamicSmemBytes, shared_bytes_static, num_regs, max_threads_per_block,
                         static_cast<int>(async_status), cudaGetErrorString(async_status),
                         M, K, N,
                         dtypeNameFromId(m_input_dtype_id),
                         dtypeNameFromId(m_output_dtype_id));
            // Force-flush BEFORE returning the error code — TRT's PluginV3Runner
            // assertion may abort the process before our static destructor runs.
            hotstep::diag::flush();
            return -1;
        }

        hotstep::diag::log("[ConvRotInt8Linear] enqueue OK — cuLaunchKernel returned CUDA_SUCCESS.\n");
        return 0;
    } catch (...) {
        // m_M / m_K / m_N are the cached shape values from onShapeChange().
        // The local M/K/N variables are out of scope here (declared inside the
        // try block above), so use the member fields for the diagnostic message.
        hotstep::diag::log(
                     "[ConvRotInt8Linear] enqueue FAILURE: C++ exception thrown (tactic=%d, "
                     "group_size=%d, M=%d, K=%d, N=%d)\n",
                     m_tactic, m_group_size, m_M, m_K, m_N);
        hotstep::diag::flush();
        return -1;
    }
}

