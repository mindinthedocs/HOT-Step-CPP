bool ConvRotInt8LinearPlugin::initTriton() {
    if (m_module) {
        hotstep::diag::log("[ConvRotInt8Linear] initTriton: m_module already initialized=%p, "
                         "skipping.\n", m_module);
        return true;
    }

    hotstep::diag::log("[ConvRotInt8Linear] initTriton ENTER: group_size=%d, in_features=%d, "
                     "out_features=%d, has_bias=%d, input_dtype=%s (id=%d), output_dtype=%s (id=%d), "
                     "m_tactic=%d\n",
                     m_group_size, m_in_features, m_out_features, m_has_bias,
                     dtypeNameFromId(m_input_dtype_id), m_input_dtype_id,
                     dtypeNameFromId(m_output_dtype_id), m_output_dtype_id,
                     m_tactic);

    // Validate group_size — the butterfly kernel only supports powers of 4.
    if (!isValidButterflyGroupSize(m_group_size)) {
        hotstep::diag::log(
                     "[ConvRotInt8Linear] initTriton REJECT: group_size=%d is not a valid butterfly "
                     "group size (must be 0 or a power of 4: 4, 16, 64, 256, 1024).\n",
                     m_group_size);
        return false;
    }

    // Select the compiled CUBIN payload based on tactic, GROUP_SIZE, HAS_BIAS,
    // and input/output dtype. In the current sm86-first build, both tactic 0
    // and tactic 2 resolve to the same 128x128 kernel inventory.
    bool has_bias = (m_has_bias != 0);
    char const* dtype_suffix = dtypeSuffixFor(m_input_dtype_id, m_output_dtype_id);
    if (dtype_suffix == nullptr) {
        hotstep::diag::log(
                     "[ConvRotInt8Linear] No compiled cubin for input_dtype=%s, "
                     "output_dtype=%s. The Triton kernel only supports FP16-in/FP16-out "
                     "and FP32-in/FP32-out (no mixed or BF16 paths). Re-run "
                     "compile_triton_plugin_sm86.py with the needed DTYPE_CONFIGS entry.\n",
                     dtypeNameFromId(m_input_dtype_id),
                     dtypeNameFromId(m_output_dtype_id));
        return false;
    }
    bool const use_m1_specialized = (m_M == 1);
#if defined(CONVROT_INT8_HAS_M1_SPECIALIZED)
    CubinPayload cubin = use_m1_specialized
        ? selectM1Cubin(m_group_size, has_bias, dtype_suffix)
        : selectCubin(false, m_group_size, has_bias, dtype_suffix);
#else
    CubinPayload cubin = selectCubin(false, m_group_size, has_bias, dtype_suffix);
#endif

    if (cubin.data == nullptr || cubin.size == 0) {
        hotstep::diag::log(
                     "[ConvRotInt8Linear] No compiled cubin for (tactic=%d, tile=%s, "
                     "group_size=%d, has_bias=%d, dtype=%s). The current generated header "
                     "contains 128x128 variants for group sizes {0, 64, 256} × {BIAS, NOBIAS} "
                     "× {FP16IO, FP32IO}; regenerate the Triton cubin header if you need a "
                     "different inventory.\n",
                     m_tactic, use_m1_specialized ? "M1" : "128X128", m_group_size, has_bias, dtype_suffix);
        return false;
    }

    // ── Shared-memory pre-flight check ──────────────────────────────────
    unsigned int const device_max_smem = getDeviceMaxDynamicSharedMem();
    if (cubin.shared_bytes > device_max_smem) {
        hotstep::diag::log(
                     "[ConvRotInt8Linear] initTriton REJECT: cubin requires %zu bytes of dynamic "
                     "shared memory, but device only supports %u bytes (sm_86 opt-in ceiling). "
                     "Re-run compile_triton_plugin_sm86.py to regenerate the header. Config: "
                     "tactic=%d, tile=%s, group_size=%d, has_bias=%d, dtype=%s.\n",
                     cubin.shared_bytes, device_max_smem,
                     m_tactic, use_m1_specialized ? "M1" : "128X128",
                     m_group_size, has_bias, dtype_suffix);
        return false;
    }

    // ── Global module cache lookup ──────────────────────────────────────
    // The cubin data pointer is a stable .rodata address (constexpr array in
    // the cubin header). We use it as a hash key to share the loaded CUmodule
    // across all plugin instances with the same config. This eliminates the
    // 359 × cuModuleLoadData calls per DiT step that were the dominant
    // performance bottleneck (150 s/step → <2 s/step).
    void const* cache_key = cubin.data;
    {
        std::lock_guard<std::mutex> lock(moduleCacheMutex());
        auto it = moduleCache().find(cache_key);
        if (it != moduleCache().end()) {
            // Cache hit — copy the cached handles to this instance. No CUDA
            // Driver API calls, no GPU work. ~200 ns total.
            m_module      = it->second.module;
            m_kernelFunc  = it->second.func;
            m_shared_bytes = it->second.shared_bytes;
            m_block_m     = it->second.block_m;
            m_block_n     = it->second.block_n;
            hotstep::diag::log("[ConvRotInt8Linear] initTriton: cache HIT (key=%p) — "
                             "module=%p, kernelFunc=%p, shared=%zu, block_m=%d, block_n=%d.\n",
                             cache_key, m_module, m_kernelFunc, m_shared_bytes, m_block_m, m_block_n);
            return true;
        }
    }

    // ── Cache miss — load the cubin ─────────────────────────────────────
    cudaError_t preexisting_async_status = cudaPeekAtLastError();
    if (preexisting_async_status != cudaSuccess) {
        hotstep::diag::log(
                     "[ConvRotInt8Linear] WARNING: CUDA runtime already holds error before cuModuleLoadData: %d (%s). "
                     "This strongly suggests a prior kernel triggered a sticky/asynchronous fault.\n",
                     static_cast<int>(preexisting_async_status), cudaGetErrorString(preexisting_async_status));
    }

    CUmodule new_module = nullptr;
    CUresult status = cuModuleLoadData(&new_module, cubin.data);
    if (status != CUDA_SUCCESS) {
        hotstep::diag::log(
                     "[ConvRotInt8Linear] cuModuleLoadData failed: %d (tactic=%d, group_size=%d, "
                     "cubin_size=%zu, shared_required=%zu, cudaPeekAtLastError=%d (%s)).\n",
                     status, m_tactic, m_group_size, cubin.size, cubin.shared_bytes,
                     static_cast<int>(preexisting_async_status), cudaGetErrorString(preexisting_async_status));
        return false;
    }

    char const* kernel_name = use_m1_specialized
        ? "fused_convrot_gemm_rowwise_m1_kernel"
        : "fused_convrot_gemm_rowwise_kernel";
    CUfunction new_func = nullptr;
    status = cuModuleGetFunction(&new_func, new_module, kernel_name);
    if (status != CUDA_SUCCESS) {
        hotstep::diag::log("[ConvRotInt8Linear] cuModuleGetFunction failed: %d\n", status);
        cuModuleUnload(new_module);
        return false;
    }

    // ── Shared-memory opt-in ─────────────────────────────────────────────
    unsigned int const max_dynamic_smem = getDeviceMaxDynamicSharedMem();
    constexpr unsigned int kDefaultSharedMemBytes = 48 * 1024;
    if (max_dynamic_smem > kDefaultSharedMemBytes) {
        status = cuFuncSetAttribute(
            new_func,
            CU_FUNC_ATTRIBUTE_MAX_DYNAMIC_SHARED_SIZE_BYTES,
            static_cast<int>(max_dynamic_smem));
        if (status != CUDA_SUCCESS) {
            hotstep::diag::log(
                         "[ConvRotInt8Linear] cuFuncSetAttribute(MAX_DYNAMIC_SHARED_SIZE_BYTES=%u) "
                         "failed: %d\n", max_dynamic_smem, status);
            cuModuleUnload(new_module);
            return false;
        }
    }

    // ── Store in cache and in this instance ──────────────────────────────
    m_module      = new_module;
    m_kernelFunc  = new_func;
    m_shared_bytes = cubin.shared_bytes;
    m_block_m     = cubin.block_m;
    m_block_n     = cubin.block_n;

    {
        std::lock_guard<std::mutex> lock(moduleCacheMutex());
        moduleCache()[cache_key] = {new_module, new_func, cubin.shared_bytes,
                                    cubin.block_m, cubin.block_n};
    }

    hotstep::diag::log("[ConvRotInt8Linear] initTriton OK (cache MISS, now cached): module=%p, "
                     "kernelFunc=%p, kernel=%s, shared_required=%zu bytes, block_m=%d, block_n=%d, "
                     "smem_optin_ceiling=%u bytes.\n",
                     m_module, m_kernelFunc, kernel_name, m_shared_bytes,
                     m_block_m, m_block_n, max_dynamic_smem);
    return true;
}

void ConvRotInt8LinearPlugin::destroyTriton() {
    // Do NOT call cuModuleUnload here — the module is shared across all plugin
    // instances via the global module cache. Unloading it would invalidate the
    // handle for every other instance using the same cubin config, causing
    // use-after-free crashes on the next enqueue(). The modules are leaked
    // intentionally at process exit — the CUDA driver reclaims all GPU memory.
    // See the comment above moduleCache() for why static destructor cleanup
    // is unsafe (access violation after CUDA context teardown).
    //
    // We only clear the member pointers so this instance no longer references
    // the shared module. The module stays loaded for reuse by the next clone().
    m_module = nullptr;
    m_kernelFunc = nullptr;
    m_shared_bytes = 0;
    m_block_m = 128;
    m_block_n = 128;
}

