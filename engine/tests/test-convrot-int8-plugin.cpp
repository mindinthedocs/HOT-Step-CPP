/*
 * test-convrot-int8-plugin.cpp — unit test for the ConvRotInt8Linear TRT plugin.
 *
 * Validates the C++ plugin kernel against a NumPy reference implementation
 * computed in Python (via a JSON test-vector file). Built by CMake when TRT
 * is enabled; run from the engine build directory.
 *
 * The test exercises three paths:
 *   1. The CUDA kernel directly (launch_convrot_activation_quant +
 *      launch_int8_matmul_dequant_per_row) — verifies the kernel math.
 *   2. The plugin's enqueue() method — verifies the workspace management
 *      and kernel launch wrappers.
 *   3. The plugin creator's createPlugin() — verifies the field-collection
 *      deserialization path the ONNX parser uses.
 *
 * Test vectors are generated by tools/onnx-export/trt_plugins/tests/
 * generate_test_vectors.py and saved as JSON (input tensors + expected
 * output). The test loads the vectors, runs the kernel, and compares.
 *
 * Build: cmake --build . --target test-convrot-int8-plugin
 * Run:   ./test-convrot-int8-plugin <path-to-test-vectors.json>
 */

